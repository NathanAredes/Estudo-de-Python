# A função print() é usada para exibir mensagens na tela
print('\nHello World!\n') 
print('7 + 1 =', 7 + 1) # tudo que estiver dentro das aspas é o que sera escrito, as operações com numros são feitas fora delas
print('7 ' + '4') # colocar um + entre as aspas é uma forma de concatenar o que esta dentro das aspas

# Declaração de variaveis: variavel = valor
nome = 'Nathan' 
peso = 49.4
idade = 19
print('\nNome:', nome + ' \nPeso:', peso, ' \nIdade:', idade)

# A função input() é usada para receber dados do usuário
nome = input('\nInforme se nome: ')
peso = input('Informe seu peso: ')
idade = input('Informe sua idade: ')
print('\nNome:', nome + ' \nPeso:', peso, ' \nIdade:', idade)